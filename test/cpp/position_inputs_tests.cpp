TEST(WindowedInputIdsTest, HandlesOneTokenWindowAndAlignmentEdgePastSequenceLength) {
  auto make_state = [](int window_size, const std::string& alignment,
                       std::shared_ptr<PositionTestModel>& out_model,
                       std::shared_ptr<GeneratorParams>& out_params) {
    out_model = std::make_shared<PositionTestModel>(false, 1, 1);
    out_model->config_->model.decoder.inputs.input_ids = "mask32";
    out_model->config_->model.decoder.inputs.total_sequence_length = "mask32";
    out_model->config_->model.decoder.inputs.past_sequence_length = "pos32";
    Config::Model::Decoder::SlidingWindow sw{};
    sw.window_size = window_size;
    sw.alignment = alignment;
    sw.slide_inputs = true;
    out_model->config_->model.decoder.sliding_window = sw;
    out_params = std::make_shared<GeneratorParams>(*out_model);
    return std::make_unique<PositionTestState>(*out_params, *out_model);
  };

  auto run_update = [](InputIDs& ids, GeneratorParams& params, std::initializer_list<int32_t> vals) {
    auto span = params.p_device->Allocate<int32_t>(vals.size());
    std::copy(vals.begin(), vals.end(), span.CpuSpan().begin());
    ids.Update(span);
  };

  // 1. window_size=1 with a 1-token first update allocates value_ without null dereference.
  {
    std::shared_ptr<PositionTestModel> model;
    std::shared_ptr<GeneratorParams> params;
    auto state = make_state(1, "right", model, params);
    auto ids = CreateInputIDs(*state);
    ids->Add();

    run_update(*ids, *params, {7});
    ASSERT_NE(ids->Get(), nullptr);
    EXPECT_EQ(ids->Get()->GetTensorData<int32_t>()[0], 7);
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 0);

    run_update(*ids, *params, {9});
    EXPECT_EQ(ids->Get()->GetTensorData<int32_t>()[0], 9);
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 1);

    run_update(*ids, *params, {10});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 2);
  }

  // 2. Right-aligned [0, 0, 2, 3, 4, 5] counts 4 valid tokens for past_sequence_length.
  {
    std::shared_ptr<PositionTestModel> model;
    std::shared_ptr<GeneratorParams> params;
    auto state = make_state(3, "right", model, params);
    auto ids = CreateInputIDs(*state);
    ids->Add();

    run_update(*ids, *params, {0, 0, 2, 3, 4, 5});
    run_update(*ids, *params, {0, 0, 2, 3, 4, 5});
    run_update(*ids, *params, {8});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 4);
    run_update(*ids, *params, {9});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 5);
  }

  // 3. Left-aligned [0, 3, 4, 5, 0, 0] preserves leading BOS==0 and counts 4 valid tokens,
  //    and a single decode step followed by continuation keeps past_sequence_length aligned.
  {
    std::shared_ptr<PositionTestModel> model;
    std::shared_ptr<GeneratorParams> params;
    auto state = make_state(3, "left", model, params);
    auto ids = CreateInputIDs(*state);
    ids->Add();

    run_update(*ids, *params, {0, 3, 4, 5, 0, 0});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 2);
    run_update(*ids, *params, {0, 3, 4, 5, 0, 0});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 5);

    // Single decode step (5th valid token -> index 4), then continuation [6, 7, 0] (2 valid tokens).
    run_update(*ids, *params, {8});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 4);

    run_update(*ids, *params, {6, 7, 0});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 7);

    // Post-continuation decode (8th valid token -> index 7).
    run_update(*ids, *params, {9});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 7);
    run_update(*ids, *params, {10});
    EXPECT_EQ(state->GetInput("pos32")->GetTensorData<int32_t>()[0], 8);
  }
}

TEST(LogitsAllPadTest, SlicesValidBoundsOnAllPadSequences) {
  auto base_model = CreateModel(GetOrtEnv(), MODEL_PATH "engine/dummy-decoder");
  const size_t vocab_size = static_cast<size_t>(base_model->config_->model.vocab_size);

  // Single-sequence all-pad prefill uses the final prompt token slot.
  {
    auto params = std::make_shared<GeneratorParams>(*base_model);
    PositionTestState state{*params, *base_model};
    Logits logits{state};
    logits.Add();

    auto tokens = params->p_device->Allocate<int32_t>(3);
    std::fill(tokens.CpuSpan().begin(), tokens.CpuSpan().end(), base_model->config_->model.pad_token_id);
    logits.Update(tokens, 3);

    auto* raw_logits = state.outputs_[0]->GetTensorMutableData<float>();
    for (size_t pos = 0; pos < 3; ++pos) {
      for (size_t v = 0; v < vocab_size; ++v) {
        raw_logits[pos * vocab_size + v] = static_cast<float>(pos * 100 + v);
      }
    }

    auto sliced = logits.Get();
    auto sliced_cpu = sliced.CopyDeviceToCpu();
    ASSERT_EQ(sliced_cpu.size(), vocab_size);
    EXPECT_FLOAT_EQ(sliced_cpu[0], 200.0f);
    EXPECT_FLOAT_EQ(sliced_cpu[vocab_size - 1], static_cast<float>(200 + vocab_size - 1));
  }

  // Batched prefill with an all-pad batch row clamps that row to slot 0 without underflowing.
  {
    auto params = std::make_shared<GeneratorParams>(*base_model);
    params->search.batch_size = 2;
    PositionTestState state{*params, *base_model};
    Logits logits{state};
    logits.Add();

    const int32_t pad = base_model->config_->model.pad_token_id;
    std::array<int32_t, 6> batch_tokens{2, 3, pad, pad, pad, pad};
    auto tokens = params->p_device->Allocate<int32_t>(batch_tokens.size());
    std::copy(batch_tokens.begin(), batch_tokens.end(), tokens.CpuSpan().begin());
    logits.Update(tokens, 3);

    auto* raw_logits = state.outputs_[0]->GetTensorMutableData<float>();
    for (size_t b = 0; b < 2; ++b) {
      for (size_t pos = 0; pos < 3; ++pos) {
        for (size_t v = 0; v < vocab_size; ++v) {
          raw_logits[(b * 3 + pos) * vocab_size + v] = static_cast<float>(b * 1000 + pos * 100 + v);
        }
      }
    }

    auto sliced = logits.Get();
    auto sliced_cpu = sliced.CopyDeviceToCpu();
    ASSERT_EQ(sliced_cpu.size(), 2 * vocab_size);
    // Batch 0 last non-pad token is pos=1; Batch 1 is all-pad and clamps to pos=0.
    EXPECT_FLOAT_EQ(sliced_cpu[0], 100.0f);
    EXPECT_FLOAT_EQ(sliced_cpu[vocab_size], 1000.0f);
  }

  // Left-aligned sliding_window only right-pads when slide_inputs is true.
  for (bool slide_inputs : {false, true}) {
    auto model_copy = CreateModel(GetOrtEnv(), MODEL_PATH "engine/dummy-decoder");
    Config::Model::Decoder::SlidingWindow sw{};
    sw.window_size = 3;
    sw.alignment = "left";
    sw.slide_inputs = slide_inputs;
    model_copy->config_->model.decoder.sliding_window = sw;

    auto params = std::make_shared<GeneratorParams>(*model_copy);
    PositionTestState state{*params, *model_copy};
    Logits logits{state};
    logits.Add();

    auto tokens = params->p_device->Allocate<int32_t>(3);
    std::fill(tokens.CpuSpan().begin(), tokens.CpuSpan().end(), model_copy->config_->model.pad_token_id);
    logits.Update(tokens, 3);

    auto* raw_logits = state.outputs_[0]->GetTensorMutableData<float>();
    for (size_t pos = 0; pos < 3; ++pos) {
      for (size_t v = 0; v < vocab_size; ++v) {
        raw_logits[pos * vocab_size + v] = static_cast<float>(pos * 100 + v);
      }
    }

    auto sliced = logits.Get();
    auto sliced_cpu = sliced.CopyDeviceToCpu();
    ASSERT_EQ(sliced_cpu.size(), vocab_size);
    EXPECT_FLOAT_EQ(sliced_cpu[0], slide_inputs ? 0.0f : 200.0f);
  }

  // Right-aligned sliding_window (left-padded) preserves trailing PAD/EOS slot.
  {
    auto model_copy = CreateModel(GetOrtEnv(), MODEL_PATH "engine/dummy-decoder");
    Config::Model::Decoder::SlidingWindow sw{};
    sw.window_size = 3;
    sw.alignment = "right";
    sw.slide_inputs = true;
    model_copy->config_->model.decoder.sliding_window = sw;

    auto params = std::make_shared<GeneratorParams>(*model_copy);
    PositionTestState state{*params, *model_copy};
    Logits logits{state};
    logits.Add();

    const int32_t pad = model_copy->config_->model.pad_token_id;
    std::array<int32_t, 3> window_tokens{4, 5, pad};
    auto tokens = params->p_device->Allocate<int32_t>(window_tokens.size());
    std::copy(window_tokens.begin(), window_tokens.end(), tokens.CpuSpan().begin());
    logits.Update(tokens, 3);

    auto* raw_logits = state.outputs_[0]->GetTensorMutableData<float>();
    for (size_t pos = 0; pos < 3; ++pos) {
      for (size_t v = 0; v < vocab_size; ++v) {
        raw_logits[pos * vocab_size + v] = static_cast<float>(pos * 100 + v);
      }
    }

    auto sliced = logits.Get();
    auto sliced_cpu = sliced.CopyDeviceToCpu();
    ASSERT_EQ(sliced_cpu.size(), vocab_size);
    EXPECT_FLOAT_EQ(sliced_cpu[0], 200.0f);
  }
}

