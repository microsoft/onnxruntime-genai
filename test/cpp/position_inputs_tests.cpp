TEST_P(PositionInputsTest, AllPadBatchRowInitializesNextPositions) {
  Initialize(2, 1);
  const auto& pos_name = model->config_->model.decoder.inputs.position_ids;
  Update({2, 3, 0, 0, 0, 0}, 3, 3);
  ExpectMask({{1, 1, 0}, {0, 0, 0}});
  EXPECT_EQ(Read(*state->GetInput(pos_name.c_str())),
            (std::vector<int64_t>{0, 1, 0, 0, 0, 0}));
  Update({5, 6}, 4, 1);
  ExpectMask({{1, 1, 0, 1}, {0, 0, 0, 1}});
  EXPECT_EQ(Read(*state->GetInput(pos_name.c_str())),
            (std::vector<int64_t>{2, 0}));
  Update({7, 8}, 5, 1);
  ExpectMask({{1, 1, 0, 1, 1}, {0, 0, 0, 1, 1}});
  EXPECT_EQ(Read(*state->GetInput(pos_name.c_str())),
            (std::vector<int64_t>{3, 1}));

  // One-slot batched prefill does not resize on decode; still consumes -1 sentinel.
  inputs->RewindTo(0);
  Update({2, 0}, 1, 1);
  ExpectMask({{1}, {0}});
  EXPECT_EQ(Read(*state->GetInput(pos_name.c_str())),
            (std::vector<int64_t>{0, 0}));
  Update({5, 6}, 2, 1);
  ExpectMask({{1, 1}, {0, 1}});
  EXPECT_EQ(Read(*state->GetInput(pos_name.c_str())),
            (std::vector<int64_t>{1, 0}));
  Update({7, 8}, 3, 1);
  ExpectMask({{1, 1, 1}, {0, 1, 1}});
  EXPECT_EQ(Read(*state->GetInput(pos_name.c_str())),
            (std::vector<int64_t>{2, 1}));
}

