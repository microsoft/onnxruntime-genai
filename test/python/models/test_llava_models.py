"""
Tests for the "llava" model type against the tiny models in test/models/llava.

The models are generated by test/python/create/create_dummy_llava_models.py: a fixed-resolution
vision model emitting 4 features per image, an embedding model that writes them at the image token
positions, and a decoder whose logits depend on every embedding so far. Generation only matches the
plain ONNX Runtime reference when the processor expands each image token to the right number of
positions and the features reach the embedding model in order.

Run with:
    python -m pytest test/python/models/test_llava_models.py --test_models test/models
"""

from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

import numpy as np
import onnxruntime_genai as og
import pytest

IMAGE_TOKEN = "<image>"
IMAGE_TOKEN_ID = 3
TOKENS_PER_IMAGE = 4
HIDDEN_SIZE = 16


def _model_path(test_data_path) -> str:
    path = Path(test_data_path) / "llava"
    if not (path / "genai_config.json").exists():
        pytest.skip(f"llava test model not found at {path}")
    return os.fspath(path)


def _images(test_data_path, names):
    if not names:
        return None
    # Absolute paths: og.Images.open keeps pointers to the path strings.
    paths = [(Path(test_data_path).parent / "images" / name).resolve() for name in names]
    for path in paths:
        if not path.exists():
            pytest.skip(f"Test image not found at {path}")
    return og.Images.open(*[os.fspath(path) for path in paths])


def _copy_model(test_data_path, tmp_path, edit) -> str:
    destination = tmp_path / "llava"
    shutil.copytree(_model_path(test_data_path), destination)
    config_path = destination / "genai_config.json"
    config = json.loads(config_path.read_text())
    edit(config["model"])
    config_path.write_text(json.dumps(config))
    return os.fspath(destination)


def _process(model_path, prompt, images):
    model = og.Model(model_path)
    return model, model.create_multimodal_processor()(prompt, images=images)


def _generate(model_path, prompt, images, max_length):
    model, inputs = _process(model_path, prompt, images)
    params = og.GeneratorParams(model)
    params.set_search_options(do_sample=False, max_length=max_length)
    generator = og.Generator(model, params)
    generator.set_inputs(inputs)
    while not generator.is_done():
        generator.generate_next_token()
    return generator.get_sequence(0), inputs


def _reference(model_path, input_ids, pixel_values, max_length):
    """Greedy decoding of the same three graphs with plain ONNX Runtime sessions."""
    ort = pytest.importorskip("onnxruntime")

    def session(name):
        return ort.InferenceSession(os.path.join(model_path, name), providers=["CPUExecutionProvider"])

    vision, embedding, decoder = session("vision.onnx"), session("embedding.onnx"), session("decoder.onnx")
    if pixel_values is None:
        features = np.zeros((0, 0, HIDDEN_SIZE), np.float32)
    else:
        (features,) = vision.run(None, {"pixel_values": pixel_values})
    no_features = np.zeros((features.shape[0], 0, HIDDEN_SIZE), np.float32)

    tokens = [int(t) for t in input_ids]
    past = np.zeros((1, 1, 0, HIDDEN_SIZE), np.float32)
    step_ids, step_features = tokens, features
    while len(tokens) < max_length:
        (embeds,) = embedding.run(None, {"input_ids": np.array([step_ids], np.int64), "image_features": step_features})
        logits, key, value = decoder.run(
            None,
            {
                "inputs_embeds": embeds,
                "attention_mask": np.ones((1, len(tokens)), np.int64),
                "past_key_values.0.key": past,
                "past_key_values.0.value": past,
            },
        )
        past = key
        tokens.append(int(logits[0, -1].argmax()))
        step_ids, step_features = tokens[-1:], no_features
    return np.array(tokens)


def test_llava_processor_expands_the_image_token(test_data_path):
    model, inputs = _process(_model_path(test_data_path), "12<image>34", _images(test_data_path, ["cars.jpg"]))
    tokenizer = og.Tokenizer(model)

    prefix, suffix = tokenizer.encode("12").tolist(), tokenizer.encode("34").tolist()
    expected = prefix + [IMAGE_TOKEN_ID] * TOKENS_PER_IMAGE + suffix
    assert inputs["input_ids"].as_numpy()[0].tolist() == expected
    assert inputs["num_image_tokens"].as_numpy().tolist() == [TOKENS_PER_IMAGE]
    assert inputs["pixel_values"].as_numpy().shape == (1, 3, 8, 8)


def test_llava_processor_text_only(test_data_path):
    model, inputs = _process(_model_path(test_data_path), "1234", None)

    assert "pixel_values" not in inputs
    assert inputs["num_image_tokens"].as_numpy().tolist() == [0]
    np.testing.assert_array_equal(inputs["input_ids"].as_numpy()[0], og.Tokenizer(model).encode("1234"))


@pytest.mark.parametrize(
    "prompt,image_names",
    [
        ("12<image>34", ["cars.jpg"]),
        ("12<image>34", ["landscape.jpg"]),
        ("<image>5<image>67", ["cars.jpg", "landscape.jpg"]),
        ("<image>5<image>67", ["landscape.jpg", "cars.jpg"]),
        ("1234", []),
    ],
    ids=["cars", "landscape", "two-images", "two-images-swapped", "text-only"],
)
def test_llava_generation_matches_reference(test_data_path, prompt, image_names):
    model_path = _model_path(test_data_path)
    sequence, inputs = _generate(model_path, prompt, _images(test_data_path, image_names), max_length=32)

    pixel_values = inputs["pixel_values"].as_numpy() if image_names else None
    expected = _reference(model_path, inputs["input_ids"].as_numpy()[0], pixel_values, max_length=32)
    np.testing.assert_array_equal(sequence, expected)


@pytest.mark.parametrize(
    "prompt,image_names,expected",
    [
        ("1<image>2", ["cars.jpg", "landscape.jpg"], "contains 1 image tokens .* but 2 images were provided"),
        ("<image>1<image>", ["cars.jpg"], "contains 2 image tokens .* but 1 images were provided"),
        ("<image>1", [], "contains 1 image tokens .* but 0 images were provided"),
    ],
    ids=["fewer-tokens-than-images", "more-tokens-than-images", "token-without-image"],
)
def test_llava_rejects_image_token_count_mismatch(test_data_path, prompt, image_names, expected):
    with pytest.raises(RuntimeError, match=expected):
        _process(_model_path(test_data_path), prompt, _images(test_data_path, image_names))


def test_llava_num_visual_tokens_must_match_the_vision_model(test_data_path, tmp_path):
    images = _images(test_data_path, ["cars.jpg"])
    model_path = _copy_model(
        test_data_path, tmp_path, lambda model: model["vision"].__setitem__("num_visual_tokens", TOKENS_PER_IMAGE)
    )
    _, inputs = _process(model_path, "<image>", images)
    assert inputs["num_image_tokens"].as_numpy().tolist() == [TOKENS_PER_IMAGE]

    shutil.rmtree(tmp_path / "llava")
    model_path = _copy_model(
        test_data_path, tmp_path, lambda model: model["vision"].__setitem__("num_visual_tokens", 5)
    )
    with pytest.raises(RuntimeError, match="num_visual_tokens is 5 but the vision model emits 4 tokens per image"):
        og.Model(model_path).create_multimodal_processor()


def test_llava_requires_image_token_id(test_data_path, tmp_path):
    model_path = _copy_model(test_data_path, tmp_path, lambda model: model.pop("image_token_id"))
    with pytest.raises(RuntimeError, match="set model.image_token_id"):
        og.Model(model_path).create_multimodal_processor()


def test_llava_active_adapter_reaches_the_decoder(test_data_path, tmp_path):
    ort = pytest.importorskip("onnxruntime")
    onnx = pytest.importorskip("onnx")
    model_path = _copy_model(test_data_path, tmp_path, lambda model: None)
    decoder_path = os.path.join(model_path, "decoder.onnx")
    decoder = onnx.load(decoder_path)
    vocab_size = 14
    for node in decoder.graph.node:
        node.output[:] = ["base_logits" if name == "logits" else name for name in node.output]
    decoder.graph.input.append(onnx.helper.make_tensor_value_info("adapter_bias", onnx.TensorProto.FLOAT, [vocab_size]))
    decoder.graph.initializer.append(onnx.numpy_helper.from_array(np.zeros(vocab_size, np.float32), "adapter_bias"))
    decoder.graph.node.append(onnx.helper.make_node("Add", ["base_logits", "adapter_bias"], ["logits"]))
    onnx.save(decoder, decoder_path)

    favored = 9
    bias = np.zeros(vocab_size, np.float32)
    bias[favored] = 1e3
    adapter = ort.AdapterFormat()
    adapter.set_adapter_version(1)
    adapter.set_model_version(1)
    adapter.set_parameters({"adapter_bias": ort.OrtValue.ortvalue_from_numpy(bias)})
    adapter.export_adapter(os.path.join(model_path, "bias.onnx_adapter"))

    def generate(use_adapter):
        model, inputs = _process(model_path, "12<image>34", _images(test_data_path, ["cars.jpg"]))
        params = og.GeneratorParams(model)
        params.set_search_options(do_sample=False, max_length=16)
        generator = og.Generator(model, params)
        if use_adapter:
            adapters = og.Adapters(model)
            adapters.load(os.path.join(model_path, "bias.onnx_adapter"), "bias")
            generator.set_active_adapter(adapters, "bias")
        generator.set_inputs(inputs)
        while not generator.is_done():
            generator.generate_next_token()
        return generator.get_sequence(0), inputs["input_ids"].as_numpy().shape[1]

    base, prompt_length = generate(use_adapter=False)
    adapted, _ = generate(use_adapter=True)
    assert np.any(base[prompt_length:] != favored)
    assert np.all(adapted[prompt_length:] == favored)
