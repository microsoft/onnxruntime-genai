def test_lfm3_audio_restores_the_speech_slots_when_a_clip_run_throws(test_data_path, tmp_path):
    # Each clip's tensors die with its loop iteration, and get_input and get_output read the slots after the throw
    onnx = pytest.importorskip("onnx")
    model_dir = _copy_model(test_data_path, tmp_path)
    speech = onnx.load(os.fspath(model_dir / "dummy_speech.onnx"))
    # The first clip's 99 frames reshape to rows of 99 and the second clip's 49 do not, so the second run throws
    speech.graph.initializer.append(onnx.helper.make_tensor("rows_of_99", onnx.TensorProto.INT64, [2], [-1, 99]))
    speech.graph.node.append(onnx.helper.make_node("Reshape", ["input_features", "rows_of_99"], ["rows"], "check_rows"))
    speech.graph.output.append(onnx.helper.make_tensor_value_info("rows", onnx.TensorProto.FLOAT, None))
    onnx.save(speech, os.fspath(model_dir / "dummy_speech.onnx"))

    model, inputs = _process(model_dir, AUDIO_MARKER * 2, og.Audios.open(*_clips(tmp_path, 16000, 8000)))
    params = og.GeneratorParams(model)
    params.set_search_options(max_length=4096)
    generator = og.Generator(model, params)
    with pytest.raises(RuntimeError, match="check_rows"):
        generator.set_inputs(inputs)

    np.testing.assert_array_equal(generator.get_input("input_features"), inputs["audio_embeds"].as_numpy())
    assert generator.get_output("audio_features").shape == (20, 32)


def _generate_on(model_dir: Path, clips: list[str], provider: str | None, num_tokens: int):
    """Returns the generated sequence and the audio features the embedding session read."""
    config = og.Config(os.fspath(model_dir))
    config.clear_providers()
    if provider is not None:
        config.append_provider(provider)
    if provider == "cuda":
        # TF32 would move the features of encoder runs on CUDA off the CPU's
        config.set_provider_option("cuda", "use_tf32", "0")
    model = og.Model(config)
    inputs = model.create_multimodal_processor()(AUDIO_MARKER * len(clips), audios=og.Audios.open(*clips))
    generator = _generator(model, inputs)
    # The prompt has run and the speech state is gone, so this resolves to the embedding's input.
    features = generator.get_input("audio_features").copy()
    for _ in range(num_tokens):
        generator.generate_next_token()
    return generator.get_sequence(0).copy(), features


@pytest.mark.parametrize("provider", ["cuda", "webgpu"])
@pytest.mark.parametrize("speech_placement", ["cpu", "decoder"])
def test_lfm3_audio_decoder_on_another_provider_matches_cpu(test_data_path, tmp_path, provider, speech_placement):
    # append_provider moves only the decoder: a sub-model with its own session_options stays on the CPU EP.
    # "decoder" drops the speech block's session_options so the per-clip encoder runs follow the decoder and the
    # embedding session alone stays on CPU, which stages each clip's features across devices.
    if provider == "cuda" and not og.is_cuda_available():
        pytest.skip("CUDA is not available in this build")
    if provider == "webgpu" and not is_webgpu_ep_available():
        pytest.skip("the WebGPU plug-in EP is not installed")

    model_dir = _copy_model(test_data_path, tmp_path)
    if speech_placement == "decoder":
        _edit_config(model_dir, "speech.session_options", None)

    clips = _clips(tmp_path, 16000, 8000)
    expected_tokens, expected_features = _generate_on(model_dir, clips, None, num_tokens=8)
    assert expected_features.any()
    tokens, features = _generate_on(model_dir, clips, provider, num_tokens=8)
    np.testing.assert_array_equal(tokens, expected_tokens)
    np.testing.assert_allclose(features, expected_features, rtol=0, atol=1e-4)
