def test_lfm3_audio_clips_keep_their_order_and_their_own_frames(test_data_path, tmp_path):
    long_clip, short_clip = _clips(tmp_path, 16000, 8000)
    model_path = _model_path(test_data_path)
    _, one_long = _process(model_path, AUDIO_MARKER, og.Audios.open(long_clip))
    _, one_short = _process(model_path, AUDIO_MARKER, og.Audios.open(short_clip))
    long_mel, short_mel = one_long["audio_embeds"].as_numpy()[0], one_short["audio_embeds"].as_numpy()[0]

    prompt = f"{AUDIO_MARKER}and{AUDIO_MARKER}"
    model, inputs = _process(model_path, prompt, og.Audios.open(long_clip, short_clip))
    assert inputs["audio_embeds"].as_numpy().shape == (2, NUM_MELS, 99)
    np.testing.assert_array_equal(inputs["audio_embeds"].as_numpy()[0], long_mel)
    np.testing.assert_array_equal(inputs["audio_embeds"].as_numpy()[1, :, :49], short_mel)
    assert not inputs["audio_embeds"].as_numpy()[1, :, 49:].any()
    assert inputs["audio_lengths"].as_numpy().tolist() == [99, 49]
    assert inputs["audio_sizes"].as_numpy().tolist() == [13, 7]

    input_ids = inputs["input_ids"].as_numpy()[0]
    positions = np.flatnonzero(input_ids == AUDIO_TOKEN_ID)
    assert positions.size == 20
    assert positions[12] + 1 < positions[13]  # The text between the markers separates the two runs

    # Run on the padded tensor the short clip's features would move: the encoder must only see the clip's own frames
    in_order = np.concatenate([_features(test_data_path, long_mel), _features(test_data_path, short_mel)])
    generator = _generator(model, inputs)
    features = generator.get_input("audio_features")
    np.testing.assert_allclose(features, in_order, rtol=0, atol=1e-5)
    np.testing.assert_array_equal(generator.get_input("inputs_embeds")[0][input_ids == AUDIO_TOKEN_ID], features)

    swapped_inputs = model.create_multimodal_processor()(prompt, audios=og.Audios.open(short_clip, long_clip))
    swapped = _generator(model, swapped_inputs).get_input("audio_features")
    assert swapped.shape == in_order.shape
    assert not np.allclose(swapped, in_order)


