def _replace_speech_graph(model_dir: Path, elem_type: int, input_shape: list) -> None:
    """A speech graph with the given input, whose output has the input's rank."""
    onnx = pytest.importorskip("onnx")
    helper = onnx.helper
    graph = helper.make_graph(
        [
            helper.make_node("Shape", ["input_features"], ["features_shape"]),
            helper.make_node("ConstantOfShape", ["features_shape"], ["audio_features"]),
        ],
        "speech",
        [helper.make_tensor_value_info("input_features", elem_type, input_shape)],
        [helper.make_tensor_value_info("audio_features", onnx.TensorProto.FLOAT, [None] * len(input_shape))],
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 17)], ir_version=8)
    onnx.save(model, os.fspath(model_dir / "dummy_speech.onnx"))


