def test_lfm3_audio_refuses_a_retry_on_the_generator_that_refused_its_inputs(test_data_path, tmp_path):
    # A refused set_inputs leaves its inputs in the generator. The retry's 13 + 7 tokens match the refused 20, so
    # without the repeat check Run would copy the retry's 99 frames out of the refused call's 9-frame mel.
    model, refused = _process(_model_path(test_data_path), AUDIO_MARKER, og.Audios.open(*_clips(tmp_path, 1600)))
    refused["audio_sizes"] = np.array([20], np.int64)
    params = og.GeneratorParams(model)
    params.set_search_options(max_length=4096)
    generator = og.Generator(model, params)
    with pytest.raises(RuntimeError, match="clip 0 reports 9 frames and 20 tokens"):
        generator.set_inputs(refused)

    retry = model.create_multimodal_processor()(
        f"{AUDIO_MARKER}and{AUDIO_MARKER}", audios=og.Audios.open(*_clips(tmp_path, 16000, 8000))
    )
    message = r"got input_features more than once\. A failed set_inputs keeps its inputs, so retry with a new generator"
    with pytest.raises(RuntimeError, match=message):
        generator.set_inputs(retry)


