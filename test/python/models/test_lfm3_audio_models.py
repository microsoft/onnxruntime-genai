def _model_path(test_data_path) -> str:
    path = Path(test_data_path) / "lfm3-audio"
    if not (path / "genai_config.json").exists():
        pytest.skip(f"LFM3-Audio test model not found at {path}")
    return os.fspath(path)


def _copy_model(test_data_path, tmp_path) -> Path:
    destination = tmp_path / "lfm3-audio"
    shutil.copytree(_model_path(test_data_path), destination)
    return destination


def _edit_config(model_dir: Path, key: str, value):
    """Sets a dotted key of genai_config.json's model section; None removes it."""
    path = model_dir / "genai_config.json"
    config = json.loads(path.read_text(encoding="utf-8"))
    *parents, last = key.split(".")
    section = config["model"]
    for parent in parents:
        section = section[parent]
    if value is None:
        section.pop(last)
    else:
        section[last] = value
    path.write_text(json.dumps(config), encoding="utf-8")


def _cast_graph_input(path: Path, name: str):
    """Makes the graph input `name` float16, cast back to float for the nodes that read it."""
    onnx = pytest.importorskip("onnx")
    model = onnx.load(os.fspath(path))
    next(i for i in model.graph.input if i.name == name).type.tensor_type.elem_type = onnx.TensorProto.FLOAT16
    for node in model.graph.node:
        node.input[:] = [f"{name}_fp32" if x == name else x for x in node.input]
    model.graph.node.insert(0, onnx.helper.make_node("Cast", [name], [f"{name}_fp32"], to=onnx.TensorProto.FLOAT))
    onnx.save(model, os.fspath(path))


def _cast_graph_output(path: Path, name: str):
    """Makes the graph output `name` float16, cast from the float the nodes write."""
    onnx = pytest.importorskip("onnx")
    model = onnx.load(os.fspath(path))
    next(o for o in model.graph.output if o.name == name).type.tensor_type.elem_type = onnx.TensorProto.FLOAT16
    for node in model.graph.node:
        node.output[:] = [f"{name}_fp32" if x == name else x for x in node.output]
    model.graph.node.append(onnx.helper.make_node("Cast", [f"{name}_fp32"], [name], to=onnx.TensorProto.FLOAT16))
    onnx.save(model, os.fspath(path))


def _process(model_path, prompt, audios=None, images=None):
    model = og.Model(os.fspath(model_path))
    return model, model.create_multimodal_processor()(prompt, audios=audios, images=images)


def _clips(tmp_path, *num_samples):
    paths = []
    for i, samples in enumerate(num_samples):
        signal = _synthetic_signal(samples / SAMPLE_RATE, seed=i)
        paths.append(_write_wav(tmp_path / f"clip{i}-{samples}.wav", signal))
    return paths


def _slaney_filters(num_mels: int) -> np.ndarray:
    def hz_to_mel(hz):
        return 3 * hz / 200 if hz < 1000 else 15 + math.log(hz / 1000) * 27 / math.log(6.4)

    def mel_to_hz(mel):
        return np.where(mel < 15, 200 * mel / 3, 1000 * np.exp((mel - 15) * math.log(6.4) / 27))

    edges = mel_to_hz(np.linspace(0, hz_to_mel(SAMPLE_RATE / 2), num_mels + 2))
    bins = np.linspace(0, SAMPLE_RATE / 2, FFT_SIZE // 2 + 1)
    rise = (bins - edges[:-2, None]) / (edges[1:-1, None] - edges[:-2, None])
    fall = (edges[2:, None] - bins) / (edges[2:, None] - edges[1:-1, None])
    return np.maximum(0, np.minimum(rise, fall)) * 2 / (edges[2:, None] - edges[:-2, None])


def _num_frames(num_samples: int) -> int:
    padded = max(FFT_SIZE, num_samples + (FFT_SIZE - num_samples) % HOP_LENGTH)
    return 1 + (padded - FFT_SIZE) // HOP_LENGTH


def _reference_mel(samples: np.ndarray, num_mels: int = NUM_MELS) -> tuple[np.ndarray, np.ndarray]:
    """Log mel in float64 with the formula of the checkpoint's extractor, and the band power it comes from."""
    frames = _num_frames(len(samples))
    padded = np.zeros((frames - 1) * HOP_LENGTH + FFT_SIZE)
    padded[: len(samples)] = samples
    window = 0.5 - 0.5 * np.cos(2 * np.pi * np.arange(FFT_SIZE) / FFT_SIZE)
    windows = np.stack([padded[t * HOP_LENGTH : t * HOP_LENGTH + FFT_SIZE] * window for t in range(frames)])
    band_power = _slaney_filters(num_mels) @ (np.abs(np.fft.rfft(windows, axis=1)) ** 2).T
    with np.errstate(divide="ignore"):
        return (np.maximum(np.log10(band_power), -12.0) + 4) / 4, band_power


def _assert_mel_close(mel: np.ndarray, samples: np.ndarray):
    # Bounds from real clips: rounding of float32 FFTs moves near-silent bands by up to 0.0085 in normalized units
    expected, band_power = _reference_mel(samples)
    assert mel.shape == expected.shape
    assert np.abs(mel - expected).max() <= 0.02
    audible = band_power >= 1e-6
    assert audible.any()
    assert np.abs(mel - expected)[audible].max() <= 1e-4


