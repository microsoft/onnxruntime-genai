"""
Tests for the LFM3-VL pipeline against the tiny models in test/models/lfm3-vl.

The models are generated by test/python/create/create_dummy_lfm3_vl_models.py. The vision model takes one image per
run and the embedding model scatters its features over the <|image|> tokens, so the prompt's embeddings only match the
hand-run onnxruntime reference when the per-image vision runs and the hand-off to the embedding model agree. The
reference reads the processor's own output, so other tests check the processor.

Run with:
    python -m pytest test/python/models/test_lfm3_vl_models.py --test_models test/models
"""

from __future__ import annotations

import json
import os
import shutil
import struct
import sys
import zlib
from pathlib import Path

import numpy as np
import onnxruntime_genai as og
import pytest
from _test_utils import is_webgpu_ep_available

IMAGE_TOKEN = "<|image|>"
VISION_START = "<|vision_start|>"
VISION_END = "<|vision_end|>"
PATCH_SIZE = 16
MERGE_SIZE = 2
ROW_WIDTH = 3 * 2 * PATCH_SIZE**2


def _model_path(test_data_path) -> str:
    path = Path(test_data_path) / "lfm3-vl"
    if not (path / "genai_config.json").exists():
        pytest.skip(f"LFM3-VL test model not found at {path}")
    return os.fspath(path)


def _copy_model(test_data_path, tmp_path) -> Path:
    destination = tmp_path / "lfm3-vl"
    shutil.copytree(_model_path(test_data_path), destination)
    return destination


def _edit_json(path: Path, edit):
    config = json.loads(path.read_text(encoding="utf-8"))
    edit(config)
    path.write_text(json.dumps(config), encoding="utf-8")


def _png(pixels: np.ndarray) -> bytes:
    """Encodes an [H, W, 3] uint8 array as an RGB PNG."""

    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    height, width, _ = pixels.shape
    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    rows = b"".join(b"\x00" + row.tobytes() for row in pixels)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows)) + chunk(b"IEND", b"")


def _random_pixels(height: int, width: int, seed: int = 0) -> np.ndarray:
    return np.random.default_rng(seed).integers(0, 256, (height, width, 3), dtype=np.uint8)


def _images(*sizes):
    return og.Images.open_bytes(
        *(_png(_random_pixels(height, width, seed)) for seed, (height, width) in enumerate(sizes))
    )


def _prompt(num_images: int, text: str = "Describe.") -> str:
    return f"{VISION_START}{IMAGE_TOKEN}{VISION_END}" * num_images + text


def _process(model_path, prompt, images):
    model = og.Model(os.fspath(model_path))
    return model, model.create_multimodal_processor()(prompt, images=images)


def _image_runs(input_ids: np.ndarray, tokenizer) -> list[int]:
    """Lengths of the <|image|> runs between each vision start and end marker, in order."""
    image_id = tokenizer.to_token_id(IMAGE_TOKEN)
    starts = np.flatnonzero(input_ids == tokenizer.to_token_id(VISION_START))
    ends = np.flatnonzero(input_ids == tokenizer.to_token_id(VISION_END))
    assert len(starts) == len(ends)
    assert all(np.all(input_ids[start + 1 : end] == image_id) for start, end in zip(starts, ends, strict=True))
    return [int(end - start - 1) for start, end in zip(starts, ends, strict=True)]


def _checkpoint_layout(pixels: np.ndarray) -> np.ndarray:
    """The rows the checkpoint's image processor writes: the image twice in time, rows 2x2 block by block, and each
    row a patch as (channel, time, y, x)."""
    image = ((pixels.astype(np.float32) / 255 - 0.5) / 0.5).transpose(2, 0, 1)
    rows, cols = image.shape[1] // PATCH_SIZE, image.shape[2] // PATCH_SIZE
    clip = np.stack([image, image]).reshape(
        2, 3, rows // MERGE_SIZE, MERGE_SIZE, PATCH_SIZE, cols // MERGE_SIZE, MERGE_SIZE, PATCH_SIZE
    )
    return clip.transpose(2, 5, 3, 6, 1, 0, 4, 7).reshape(rows * cols, ROW_WIDTH)


def test_lfm3_vl_processor_writes_the_checkpoint_layout_for_images_of_different_shapes(test_data_path):
    # Sides that are multiples of 32 need no resize, so every value is known. The landscape is shorter but wider than
    # the portrait, so stacking the images by the larger [C, H, W] would not fit it.
    model, inputs = _process(_model_path(test_data_path), _prompt(2), _images((320, 256), (256, 512)))

    np.testing.assert_array_equal(inputs["image_grid_thw"].as_numpy(), [[1, 20, 16], [1, 16, 32]])
    first, second = _checkpoint_layout(_random_pixels(320, 256, 0)), _checkpoint_layout(_random_pixels(256, 512, 1))
    np.testing.assert_allclose(inputs["pixel_values"].as_numpy(), np.concatenate([first, second]), rtol=0, atol=1e-6)
    assert _image_runs(inputs["input_ids"].as_numpy()[0], og.Tokenizer(model)) == [80, 128]
    assert inputs["num_image_tokens"].as_numpy().tolist() == [208]


# smart_resize: sides rounded to multiples of 32 pixels, scaled up to at least 65536 pixels (64 tokens)
@pytest.mark.parametrize("height, width, rows, cols", [(64, 64, 16, 16), (100, 700, 6, 44), (1000, 1500, 62, 94)])
def test_lfm3_vl_processor_resizes_to_the_smart_resize_grid(test_data_path, height, width, rows, cols):
    model, inputs = _process(_model_path(test_data_path), _prompt(1), _images((height, width)))

    np.testing.assert_array_equal(inputs["image_grid_thw"].as_numpy(), [[1, rows, cols]])
    assert inputs["pixel_values"].as_numpy().shape == (rows * cols, ROW_WIDTH)
    assert _image_runs(inputs["input_ids"].as_numpy()[0], og.Tokenizer(model)) == [rows * cols // 4]


