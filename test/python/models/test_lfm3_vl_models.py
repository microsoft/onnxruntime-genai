def _generator(model, inputs, chunk_size=None, max_length=4096):
    params = og.GeneratorParams(model)
    params.set_search_options(
        do_sample=False, max_length=max_length, **({"chunk_size": chunk_size} if chunk_size else {})
    )
    generator = og.Generator(model, params)
    generator.set_inputs(inputs)
    return generator


def _reference_generation(
    model_path, inputs, num_tokens: int, zero_features: bool = False
) -> tuple[np.ndarray, np.ndarray]:
    """Greedy generation replayed with plain ONNX Runtime: one vision run per image, then the prompt through the
    embedding and decoder models, then one run per token, carrying the KV cache and conv state by hand. Returns the
    sequence and the prompt's embeddings."""
    ort = pytest.importorskip("onnxruntime")
    config = json.loads((Path(model_path) / "genai_config.json").read_text(encoding="utf-8"))["model"]
    decoder_config = config["decoder"]
    session = {
        name: ort.InferenceSession(os.path.join(model_path, config[name]["filename"]))
        for name in ("vision", "embedding", "decoder")
    }
    output_names = [output.name for output in session["decoder"].get_outputs()]
    hidden_size = decoder_config["hidden_size"]

    features = [np.zeros((0, hidden_size), np.float32)]
    if "pixel_values" in inputs:
        pixel_values, offset = inputs["pixel_values"].as_numpy(), 0
        for grid in inputs["image_grid_thw"].as_numpy():
            rows = int(grid[1] * grid[2])
            feeds = {"pixel_values": pixel_values[offset : offset + rows], "image_grid_thw": grid[None]}
            image_features = session["vision"].run(None, feeds)[0]
            features.append(np.zeros_like(image_features) if zero_features else image_features)
            offset += rows

    state = {}
    for layer, layer_type in enumerate(decoder_config["layer_types"]):
        if layer_type == "conv":
            state[f"past.{layer}.conv"] = np.zeros((1, hidden_size, decoder_config["conv_cache_size"]), np.float32)
        else:
            for kind in ("key", "value"):
                shape = (1, decoder_config["num_key_value_heads"], 0, decoder_config["head_size"])
                state[f"past_key_values.{layer}.{kind}"] = np.zeros(shape, np.float32)

    sequence = [int(token) for token in inputs["input_ids"].as_numpy()[0]]
    feeds = {"input_ids": np.array([sequence], np.int64), "image_features": np.concatenate(features)}
    embeds = prompt_embeds = session["embedding"].run(None, feeds)[0]
    for _ in range(num_tokens):
        feeds = {"inputs_embeds": embeds, "attention_mask": np.ones((1, len(sequence)), np.int64), **state}
        outputs = dict(zip(output_names, session["decoder"].run(None, feeds), strict=True))
        for name in state:
            state[name] = outputs[name.replace("past_key_values.", "present.").replace("past.", "present.")]
        sequence.append(int(outputs["logits"][0, -1].argmax()))
        feeds = {"input_ids": np.array([sequence[-1:]], np.int64), "image_features": features[0]}
        embeds = session["embedding"].run(None, feeds)[0]
    return np.array(sequence, np.int32), prompt_embeds


@pytest.mark.parametrize(
    "sizes, chunk_size",
    [([], None), ([(256, 320)], None), ([(256, 320)], 3), ([(320, 256), (256, 512), (256, 256)], None)],
    ids=["text", "image", "image-chunk3", "three-images"],
)
def test_lfm3_vl_generation_matches_onnxruntime_reference(test_data_path, sizes, chunk_size):
    # The sampled tokens read only the last 3 embeddings, all text here, so the prompt's embeddings are compared too:
    # each image's features must land on its own <|image|> run, in image order
    model_path = _model_path(test_data_path)
    model, inputs = _process(model_path, _prompt(len(sizes)), _images(*sizes) if sizes else None)
    generator = _generator(model, inputs, chunk_size)
    embeds = generator.get_input("inputs_embeds")
    for _ in range(6):
        generator.generate_next_token()

    sequence, expected_embeds = _reference_generation(model_path, inputs, 6)
    np.testing.assert_array_equal(generator.get_sequence(0), sequence)
    np.testing.assert_allclose(embeds, expected_embeds, rtol=0, atol=1e-5)
    # The comparison sees the features: zeroing them in the replay changes exactly the <|image|> rows
    _, zeroed_embeds = _reference_generation(model_path, inputs, 0, zero_features=True)
    is_image = inputs["input_ids"].as_numpy() == og.Tokenizer(model).to_token_id(IMAGE_TOKEN)
    np.testing.assert_array_equal((zeroed_embeds != expected_embeds).any(axis=-1), is_image)


