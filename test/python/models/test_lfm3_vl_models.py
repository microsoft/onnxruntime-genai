def test_lfm3_vl_casts_pixel_values_to_the_vision_input_type(test_data_path, tmp_path):
    onnx = pytest.importorskip("onnx")
    model_dir = _copy_model(test_data_path, tmp_path)
    vision = onnx.load(os.fspath(model_dir / "dummy_vision.onnx"))
    vision.graph.input[0].type.tensor_type.elem_type = onnx.TensorProto.FLOAT16
    vision.graph.node.insert(0, onnx.helper.make_node("Cast", ["pixel_values"], ["pixels_fp32"], to=1))
    for node in vision.graph.node[1:]:
        node.input[:] = ["pixels_fp32" if name == "pixel_values" else name for name in node.input]
    onnx.save(vision, os.fspath(model_dir / "dummy_vision.onnx"))

    sizes = [(256, 320), (256, 256)]
    fp32_model, expected = _process(_model_path(test_data_path), _prompt(2), _images(*sizes))
    model, inputs = _process(model_dir, _prompt(2), _images(*sizes))
    pixel_values = inputs["pixel_values"].as_numpy()
    assert pixel_values.dtype == np.float16
    np.testing.assert_array_equal(pixel_values, expected["pixel_values"].as_numpy().astype(np.float16))
    # The vision session must accept the cast rows, one image per run, and give the features of the fp32 model
    generator = _generator(model, inputs)
    generator.generate_next_token()
    fp32_generator = _generator(fp32_model, expected)
    fp32_generator.generate_next_token()
    features = generator.get_input("image_features")
    assert features.shape == (80 + 64, 32)
    np.testing.assert_allclose(features, fp32_generator.get_input("image_features"), rtol=0, atol=1e-2)


def _generate_on(model_dir: Path, provider: str | None, num_tokens: int) -> tuple[np.ndarray, np.ndarray]:
    """Returns the generated sequence and the image features the embedding session read."""
    config = og.Config(os.fspath(model_dir))
    config.clear_providers()
    if provider is not None:
        config.append_provider(provider)
    if provider == "cuda":
        # TF32 would move the features of vision runs on CUDA off the CPU's
        config.set_provider_option("cuda", "use_tf32", "0")
    model = og.Model(config)
    inputs = model.create_multimodal_processor()(_prompt(2), images=_images((256, 320), (320, 256)))
    generator = _generator(model, inputs)
    # The prompt has run and the vision state is gone, so this resolves to the embedding's input.
    features = generator.get_input("image_features").copy()
    for _ in range(num_tokens):
        generator.generate_next_token()
    return generator.get_sequence(0).copy(), features


@pytest.mark.parametrize("provider", ["cuda", "webgpu"])
@pytest.mark.parametrize("vision_placement", ["cpu", "decoder"])
def test_lfm3_vl_decoder_on_another_provider_matches_cpu(test_data_path, tmp_path, provider, vision_placement):
    # append_provider moves only the decoder: a sub-model with its own session_options stays on the CPU EP.
    # "decoder" drops the vision block's session_options so the per-image vision runs follow the decoder and the
    # embedding session alone stays on CPU, which stages each image's features across devices.
    if provider == "cuda" and not og.is_cuda_available():
        pytest.skip("CUDA is not available in this build")
    if provider == "webgpu" and not is_webgpu_ep_available():
        pytest.skip("the WebGPU plug-in EP is not installed")

    model_dir = _copy_model(test_data_path, tmp_path)
    if vision_placement == "decoder":
        _edit_json(model_dir / "genai_config.json", lambda config: config["model"]["vision"].pop("session_options"))

    expected_tokens, expected_features = _generate_on(model_dir, None, num_tokens=8)
    assert expected_features.any()
    tokens, features = _generate_on(model_dir, provider, num_tokens=8)
    np.testing.assert_array_equal(tokens, expected_tokens)
    np.testing.assert_allclose(features, expected_features, rtol=0, atol=1e-4)


def test_lfm3_vl_builder_makes_a_working_pipeline(test_data_path, tmp_path):
    # With exclude_embeds=true the model builder writes the vision and embedding models and processor_config.json.
    # Run on the stand-in checkpoint of the builder tests, each image's features must match the vision math on the
    # rows the runtime's processor wrote, and land on that image's <|image|> tokens.
    torch = pytest.importorskip("torch")
    pytest.importorskip("transformers")
    pytest.importorskip("onnx_ir")
    builder_tests_dir = str(Path(__file__).resolve().parents[1] / "builder")
    if builder_tests_dir not in sys.path:
        sys.path.insert(0, builder_tests_dir)
    from _builder_test_utils import ort_runs_causal_conv_with_state  # noqa: PLC0415

    if not ort_runs_causal_conv_with_state():
        pytest.skip("this onnxruntime cannot run com.microsoft:CausalConvWithState")
    import test_lfm3_vl as builder_tests  # noqa: PLC0415

    config = builder_tests.stand_in_config(tmp_path)
    config.text_config.max_position_embeddings = 1024  # Room for the two images' 160 tokens
    config.text_config.head_dim = 16  # GroupQueryAttention runs head sizes that are multiples of 8
    tokenizer = json.loads((Path(_model_path(test_data_path)) / "tokenizer.json").read_text(encoding="utf-8"))
    config.image_token_id = next(t["id"] for t in tokenizer["added_tokens"] if t["content"] == IMAGE_TOKEN)
    model, hf_model = builder_tests.build_pipeline(
        tmp_path,
        config,
        builder_tests.ir.DataType.FLOAT,
        builder_tests.ir.DataType.FLOAT,
        "cpu",
        {"exclude_embeds": True},
    )
    output = tmp_path / "model"
    output.mkdir()
    model.save_model(os.fspath(output))
    model.make_genai_config(config, {}, os.fspath(output))
    for name in ("tokenizer.json", "tokenizer_config.json"):
        shutil.copy(Path(_model_path(test_data_path)) / name, output / name)

    og_model = og.Model(os.fspath(output))
    # Images with different token counts, so a run given to the wrong image changes the run lengths
    inputs = og_model.create_multimodal_processor()(_prompt(2), images=_images((64, 96), (64, 64)))
    generator = _generator(og_model, inputs, max_length=1024)

    pixel_values, offset, expected = inputs["pixel_values"].as_numpy(), 0, []
    for _, rows, cols in inputs["image_grid_thw"].as_numpy():
        with torch.no_grad():
            image_rows = torch.from_numpy(pixel_values[offset : offset + rows * cols])
            expected.append(builder_tests.expected_features(hf_model, image_rows, int(rows), int(cols)).numpy())
        offset += rows * cols
    features = generator.get_input("image_features")
    np.testing.assert_allclose(features, np.concatenate(expected), rtol=1e-4, atol=1e-5)

    input_ids = inputs["input_ids"].as_numpy()[0]
    is_image = input_ids == config.image_token_id
    embeds = generator.get_input("inputs_embeds")[0]
    assert _image_runs(input_ids, og.Tokenizer(og_model)) == [len(e) for e in expected] == [96, 64]
    assert is_image.sum() == len(features)
    np.testing.assert_array_equal(embeds[is_image], features)
    generator.generate_next_token()
    assert generator.get_sequence(0).shape[0] == len(input_ids) + 1
