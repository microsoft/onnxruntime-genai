# Bicubic rounds a handful of pixels one level further than bilinear.
@pytest.mark.parametrize("interpolation,resample,max_levels", [("LINEAR", 2, 1), ("CUBIC", 3, 2)])
@pytest.mark.parametrize("image_name", ["cars.jpg", "10809054.jpg"])
def test_lfm2_vl_pixels_match_hugging_face(test_data_path, tmp_path, interpolation, resample, max_levels, image_name):
    transformers = pytest.importorskip("transformers")
    pytest.importorskip("torchvision")
    image_module = pytest.importorskip("PIL.Image")
    processor_class = getattr(transformers, "Lfm2VlImageProcessor", None)
    if processor_class is None:
        pytest.skip("transformers has no Lfm2VlImageProcessor")

    model_dir = _copy_model(test_data_path, tmp_path)

    def set_interpolation(config):
        for transform in config["processor"]["transforms"]:
            if transform["operation"]["type"] == "Resize":
                transform["operation"]["attrs"]["interpolation"] = interpolation

    _edit_json(model_dir / "processor_config.json", set_interpolation)

    # Decode once with PIL and hand both processors the same RGB pixels. JPEG decoders legitimately
    # differ by tens of levels on edges, which would hide a real resize or normalization difference.
    image = image_module.open(_image_path(test_data_path, image_name)).convert("RGB")
    png = io.BytesIO()
    image.save(png, format="PNG")

    _, inputs = _process(os.fspath(model_dir), "<image>x", og.Images.open_bytes(png.getvalue()))
    reference = processor_class(do_image_splitting=False, resample=resample)(images=[[image]], return_tensors="np")

    np.testing.assert_array_equal(inputs["image_sizes"].as_numpy(), reference["spatial_shapes"])
    np.testing.assert_array_equal(inputs["image_attention_mask"].as_numpy(), reference["pixel_attention_mask"])
    num_patches = int(reference["pixel_attention_mask"].sum())
    np.testing.assert_allclose(
        inputs["pixel_values"].as_numpy()[0, :num_patches],
        reference["pixel_values"][0, :num_patches],
        rtol=0,
        atol=ONE_PIXEL_LEVEL * max_levels * 1.01,
    )


def _reference_generation(model_path: str, input_ids: np.ndarray, num_tokens: int) -> np.ndarray:
    """Greedy generation replayed with plain ONNX Runtime.

    One prefill run, then one run per token, carrying the KV cache and conv state by hand. The stub
    embedding and decoder ignore the image features, so the prompt token ids are all it needs.
    """
    ort = pytest.importorskip("onnxruntime")
    config = json.loads((Path(model_path) / "genai_config.json").read_text())["model"]
    decoder_config = config["decoder"]
    embedding = ort.InferenceSession(os.path.join(model_path, config["embedding"]["filename"]))
    decoder = ort.InferenceSession(os.path.join(model_path, decoder_config["filename"]))
    output_names = [output.name for output in decoder.get_outputs()]

    hidden_size = decoder_config["hidden_size"]
    state = {}
    for layer, layer_type in enumerate(decoder_config["layer_types"]):
        if layer_type == "conv":
            state[f"past.{layer}.conv"] = np.zeros((1, hidden_size, decoder_config["conv_cache_size"]), np.float32)
        else:
            for kind in ("key", "value"):
                state[f"past_key_values.{layer}.{kind}"] = np.zeros(
                    (1, decoder_config["num_key_value_heads"], 0, decoder_config["head_size"]), np.float32
                )

    sequence = [int(token) for token in input_ids]
    step_ids = sequence
    for _ in range(num_tokens):
        embeds = embedding.run(
            None,
            {
                "input_ids": np.array([step_ids], dtype=np.int64),
                "image_features": np.zeros((0, hidden_size), np.float32),
            },
        )[0]
        feeds = {"inputs_embeds": embeds, "attention_mask": np.ones((1, len(sequence)), np.int64), **state}
        outputs = dict(zip(output_names, decoder.run(None, feeds), strict=True))
        for name in state:
            state[name] = outputs[name.replace("past_key_values.", "present.").replace("past.", "present.")]
        next_token = int(outputs["logits"][0, -1].argmax())
        sequence.append(next_token)
        step_ids = [next_token]
    return np.array(sequence, dtype=np.int32)


@pytest.mark.parametrize(
    "with_image,chunk_size",
    [(False, None), (False, 3), (True, None), (True, 3), (True, 64)],
    ids=["text", "text-chunk3", "image", "image-chunk3", "image-chunk64"],
)
def test_lfm2_vl_generation_matches_onnxruntime_reference(test_data_path, with_image, chunk_size):
    # The decoder's logits read the conv state, so the runtime only matches the hand-carried
    # reference if it passes that state between runs, including across prefill chunk boundaries.
    model_path = _model_path(test_data_path)
    images = og.Images.open(_image_path(test_data_path, "cars.jpg")) if with_image else None
    prompt = "<image>Describe this image." if with_image else "Describe this image in detail please."
    num_tokens = 6

    generator, inputs = _generate(model_path, prompt, images, num_tokens, chunk_size=chunk_size)
    input_ids = inputs["input_ids"].as_numpy()[0]
    assert chunk_size is None or len(input_ids) > chunk_size, "the prompt must span several chunks"

    np.testing.assert_array_equal(generator.get_sequence(0), _reference_generation(model_path, input_ids, num_tokens))


def test_lfm2_vl_rejects_rewind(test_data_path):
    generator, _ = _generate(
        _model_path(test_data_path), "<image>Hi", og.Images.open(_image_path(test_data_path, "cars.jpg")), num_tokens=1
    )
    sequence = generator.get_sequence(0).copy()

    # The conv state cannot be rewound; the generator must refuse before touching the sequence.
    with pytest.raises(RuntimeError, match="RewindTo is currently not supported for lfm2_vl"):
        generator.rewind_to(0)
    np.testing.assert_array_equal(generator.get_sequence(0), sequence)
