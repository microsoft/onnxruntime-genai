def test_lfm2_audio_mel_matches_liquid_audio(test_data_path, tmp_path):
    """The reference implementation itself, when the liquid-audio package is installed."""
    torch = pytest.importorskip("torch")
    processor_module = pytest.importorskip("liquid_audio.model.conformer.processor")
    reference_processor = processor_module.AudioToMelSpectrogramPreprocessor(**PREPROCESSOR_CONFIG).eval()

    samples = _synthetic_signal(1.5, seed=5)
    clip = _write_wav(tmp_path / "clip.wav", samples)
    _, inputs = _process(_model_path(test_data_path), AUDIO_MARKER, og.Audios.open(clip))
    mel = inputs["audio_embeds"].as_numpy()[0]

    with torch.no_grad():
        wave_tensor = torch.from_numpy(samples)[None, :]
        reference, _ = reference_processor(wave_tensor, torch.tensor([wave_tensor.shape[1]]))
    np.testing.assert_allclose(mel, reference[0].T.numpy(), atol=2e-3)


def test_lfm2_audio_casts_mel_to_the_speech_input_type(test_data_path, tmp_path):
    onnx = pytest.importorskip("onnx")
    model_path = _copy_model(test_data_path, tmp_path)
    speech_path = model_path / "dummy_speech.onnx"
    speech = onnx.load(speech_path)
    # Take mel_spectrogram as float16 and cast it back to float32 for the rest of the graph.
    speech.graph.input[0].type.tensor_type.elem_type = onnx.TensorProto.FLOAT16
    for node in speech.graph.node:
        node.input[:] = ["mel_spectrogram_fp16" if name == "mel_spectrogram" else name for name in node.input]
    speech.graph.node.insert(
        0, onnx.helper.make_node("Cast", ["mel_spectrogram"], ["mel_spectrogram_fp16"], to=onnx.TensorProto.FLOAT)
    )
    onnx.save(speech, speech_path)

    samples = _synthetic_signal(0.7, seed=6)
    clip = _write_wav(tmp_path / "clip.wav", samples)
    _, inputs = _process(os.fspath(model_path), AUDIO_MARKER, og.Audios.open(clip))
    mel = inputs["audio_embeds"].as_numpy()
    assert mel.dtype == np.float16
    np.testing.assert_allclose(mel[0].astype(np.float32), _reference_mel(samples), atol=2e-2)

    # And the fp16 features still flow through generation.
    generator, _ = _generate(os.fspath(model_path), AUDIO_MARKER, og.Audios.open(clip), num_tokens=2)
    assert len(generator.get_sequence(0)) == mel.shape[1] // SUBSAMPLING_FACTOR + 1 + 2


