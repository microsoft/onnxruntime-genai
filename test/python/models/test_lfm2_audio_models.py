"""
Tests for the LFM2-Audio pipeline against the tiny models in test/models/lfm2-audio.

The models are generated by test/python/create/create_dummy_lfm2_audio_models.py, and the tokenizer
is checked in zipped alongside them, so `_model_path` assembles a runnable model directory in a
temporary directory once per session. The speech model
emits one feature per 8 mel frames, the embedding model scatters those features over the placeholders
the processor writes, and the decoder's logits depend on the conv state, so generation only succeeds,
and only matches between runs, when the processor, the speech/embedding hand-off and the conv state
cache agree.

Run with:
    python -m pytest test/python/models/test_lfm2_audio_models.py --test_models test/models
"""

from __future__ import annotations

import json
import math
import os
import shutil
import tempfile
import wave
import zipfile
from pathlib import Path

import numpy as np
import onnxruntime_genai as og
import pytest

AUDIO_MARKER = "<|audio|>"
AUDIO_START_TOKEN_ID = 128  # <|audio_start|>: the model switching from text to speech
AUDIO_TOKEN_ID = 133  # <|reserved_123|>, model.audio_token_id in the fixture's genai_config.json
NUM_MELS = 128
SAMPLE_RATE = 16000
FFT_SIZE = 512
WIN_LENGTH = 400
HOP_LENGTH = 160
SUBSAMPLING_FACTOR = 8
LOG_EPS = 2.0**-24
NORM_EPS = 1e-5
# Settings of LiquidAI/LFM2-Audio-1.5B and LFM2.5-Audio-1.5B (config.json "preprocessor").
PREPROCESSOR_CONFIG = {
    "sample_rate": SAMPLE_RATE,
    "normalize": "per_feature",
    "window_size": 0.025,
    "window_stride": 0.01,
    "window": "hann",
    "features": NUM_MELS,
    "n_fft": FFT_SIZE,
    "log": True,
    "frame_splicing": 1,
    "dither": 1.0e-05,
    "pad_to": 0,
    "pad_value": 0.0,
}


# The tokenizer is checked in zipped: its 4.8 MB of vocabulary compresses to under 1 MB, and no test
# reads it as text. Refresh it with, from the model directory,
#   python -c "import zipfile; \
#              [zipfile.ZipFile('tokenizer.zip', 'w').writestr(n, open(n, 'rb').read()) for n in NAMES]"
# or take a fresh copy from LiquidAI/LFM2.5-Audio-1.5B.
TOKENIZER_ARCHIVE = "tokenizer.zip"
TOKENIZER_FILES = ("tokenizer.json", "tokenizer_config.json")

# One assembled directory per source, kept alive (and so undeleted) for the whole session.
_MODEL_DIRECTORIES: dict[str, tempfile.TemporaryDirectory] = {}


def _model_path(test_data_path) -> str:
    """The fixture model directory, with the tokenizer unpacked, assembled once per session.

    Everything the runtime loads has to sit in one directory, so the ONNX models and the config are
    copied next to the unpacked tokenizer rather than the archive being unpacked over the checkout.
    """
    source = Path(test_data_path) / "lfm2-audio"
    if not (source / "genai_config.json").exists():
        pytest.skip(f"LFM2-Audio test model not found at {source}")

    key = os.fspath(source)
    if key not in _MODEL_DIRECTORIES:
        holder = tempfile.TemporaryDirectory(prefix="lfm2-audio-")
        destination = Path(holder.name)
        for item in source.iterdir():
            if item.is_file() and item.name != TOKENIZER_ARCHIVE:
                shutil.copy(item, destination)
        with zipfile.ZipFile(source / TOKENIZER_ARCHIVE) as archive:
            # Named rather than extractall: the archive holds exactly these two files, and naming
            # them keeps a stray path in the archive from landing outside the directory.
            for name in TOKENIZER_FILES:
                (destination / name).write_bytes(archive.read(name))
        _MODEL_DIRECTORIES[key] = holder
    return _MODEL_DIRECTORIES[key].name


def _copy_model(test_data_path, tmp_path) -> Path:
    destination = tmp_path / "lfm2-audio"
    shutil.copytree(_model_path(test_data_path), destination)
    return destination


def _edit_json(path: Path, edit):
    config = json.loads(path.read_text())
    edit(config)
    path.write_text(json.dumps(config))


def _synthetic_signal(seconds: float, seed: int = 0) -> np.ndarray:
    """A few tones plus noise, quantized to 16-bit like the WAV that carries it."""
    rng = np.random.default_rng(seed)
    t = np.arange(int(seconds * SAMPLE_RATE)) / SAMPLE_RATE
    signal = 0.3 * np.sin(2 * np.pi * 440 * t) + 0.1 * np.sin(2 * np.pi * 3000 * t) + 0.05 * rng.standard_normal(t.size)
    return np.round(np.clip(signal, -1, 1) * 32767).astype(np.int16).astype(np.float32) / 32768.0


def _write_wav(path: Path, samples: np.ndarray, sample_rate: int = SAMPLE_RATE, channels: int = 1) -> str:
    pcm = np.round(samples * 32768.0).clip(-32768, 32767).astype("<i2")
    if channels > 1:
        pcm = np.repeat(pcm[:, None], channels, axis=1)
    with wave.open(os.fspath(path), "wb") as handle:
        handle.setnchannels(channels)
        handle.setsampwidth(2)
        handle.setframerate(sample_rate)
        handle.writeframes(pcm.tobytes())
    return os.fspath(path)


def _num_frames(num_samples: int) -> int:
    # torch.stft(center=True): one frame per hop plus one.
    return num_samples // HOP_LENGTH + 1


def _num_tokens(num_samples: int) -> int:
    return math.ceil(_num_frames(num_samples) / SUBSAMPLING_FACTOR)


def _slaney_mel_filterbank() -> np.ndarray:
    """librosa.filters.mel(sr, n_fft, n_mels, fmin=0, fmax=sr/2, norm="slaney") without librosa."""

    def hz_to_mel(hz):
        hz = np.asarray(hz, dtype=np.float64)
        mel = hz / (200.0 / 3)
        log_region = hz >= 1000.0
        mel[log_region] = 15.0 + np.log(hz[log_region] / 1000.0) / (np.log(6.4) / 27.0)
        return mel

    def mel_to_hz(mel):
        mel = np.asarray(mel, dtype=np.float64)
        hz = mel * (200.0 / 3)
        log_region = mel >= 15.0
        hz[log_region] = 1000.0 * np.exp((np.log(6.4) / 27.0) * (mel[log_region] - 15.0))
        return hz

    fft_freqs = np.linspace(0, SAMPLE_RATE / 2, FFT_SIZE // 2 + 1)
    mel_points = mel_to_hz(np.linspace(hz_to_mel([0.0])[0], hz_to_mel([SAMPLE_RATE / 2])[0], NUM_MELS + 2))
    fdiff = np.diff(mel_points)
    ramps = mel_points[:, None] - fft_freqs[None, :]
    weights = np.maximum(0, np.minimum(-ramps[:-2] / fdiff[:-1, None], ramps[2:] / fdiff[1:, None]))
    weights *= (2.0 / (mel_points[2 : NUM_MELS + 2] - mel_points[:NUM_MELS]))[:, None]
    return weights.astype(np.float32)


def _reference_mel(samples: np.ndarray) -> np.ndarray:
    """NeMo's AudioToMelSpectrogramPreprocessor in eval mode, as liquid-audio ships it, in numpy.

    Pre-emphasis, constant center padding, symmetric Hann window, power spectrum, Slaney mel filter
    bank, log with the 2^-24 guard, then per-feature normalization over the num_samples // hop
    frames get_seq_len counts as valid, with the frames past that zeroed.
    """
    preemphasized = np.concatenate([samples[:1], samples[1:] - 0.97 * samples[:-1]])
    padded = np.pad(preemphasized, FFT_SIZE // 2)
    num_frames = _num_frames(len(samples))
    window = np.zeros(FFT_SIZE, np.float64)
    window[(FFT_SIZE - WIN_LENGTH) // 2 :][:WIN_LENGTH] = 0.5 * (
        1 - np.cos(2 * np.pi * np.arange(WIN_LENGTH) / (WIN_LENGTH - 1))
    )
    frames = np.stack([padded[t * HOP_LENGTH : t * HOP_LENGTH + FFT_SIZE] * window for t in range(num_frames)])
    power = np.abs(np.fft.rfft(frames, axis=1)) ** 2
    log_mel = np.log(power @ _slaney_mel_filterbank().T.astype(np.float64) + LOG_EPS)

    valid = len(samples) // HOP_LENGTH
    mean = log_mel[:valid].mean(axis=0)
    std = np.sqrt(((log_mel[:valid] - mean) ** 2).sum(axis=0) / (valid - 1)) + NORM_EPS
    normalized = (log_mel - mean) / std
    normalized[valid:] = 0.0
    return normalized.astype(np.float32)


def _process(model_path: str, prompt: str, audios):
    model = og.Model(model_path)
    inputs = model.create_multimodal_processor()(prompt, audios=audios)
    return model, inputs


def _placeholder_runs(input_ids: np.ndarray) -> list[int]:
    """Lengths of the consecutive AUDIO_TOKEN_ID runs, in order."""
    runs = []
    run = 0
    for token in input_ids:
        if token == AUDIO_TOKEN_ID:
            run += 1
        elif run:
            runs.append(run)
            run = 0
    if run:
        runs.append(run)
    return runs


def test_lfm2_audio_processor_single_clip(test_data_path, tmp_path):
    samples = _synthetic_signal(1.3)
    clip = _write_wav(tmp_path / "clip.wav", samples)
    prompt = f"<|startoftext|><|im_start|>user\n{AUDIO_MARKER}<|im_end|>\n<|im_start|>assistant\n"
    model, inputs = _process(_model_path(test_data_path), prompt, og.Audios.open(clip))
    tokenizer = og.Tokenizer(model)

    # Same token stream as liquid-audio's ChatState: the text on either side of the clip is tokenized
    # on its own and one placeholder per encoder frame sits between.
    num_frames = _num_frames(len(samples))
    expected_ids = (
        tokenizer.encode("<|startoftext|><|im_start|>user\n").tolist()
        + [AUDIO_TOKEN_ID] * _num_tokens(len(samples))
        + tokenizer.encode("<|im_end|>\n<|im_start|>assistant\n").tolist()
    )
    input_ids = inputs["input_ids"].as_numpy()
    assert input_ids.shape == (1, len(expected_ids))
    assert input_ids[0].tolist() == expected_ids

    mel = inputs["audio_embeds"].as_numpy()
    assert mel.shape == (1, num_frames, NUM_MELS)
    assert mel.dtype == np.float32
    np.testing.assert_array_equal(inputs["audio_lengths"].as_numpy(), [num_frames])
    np.testing.assert_array_equal(inputs["audio_sizes"].as_numpy(), [_num_tokens(len(samples))])


def test_lfm2_audio_processor_text_only(test_data_path):
    _, inputs = _process(_model_path(test_data_path), "<|startoftext|>Just text.", None)
    assert AUDIO_TOKEN_ID not in inputs["input_ids"].as_numpy()
    np.testing.assert_array_equal(inputs["audio_sizes"].as_numpy(), [0])
    with pytest.raises(RuntimeError, match="audio_embeds"):
        _ = inputs["audio_embeds"]


def test_lfm2_audio_processor_two_clips_of_different_lengths(test_data_path, tmp_path):
    short = _synthetic_signal(0.5, seed=1)
    long = _synthetic_signal(1.7, seed=2)
    clips = [_write_wav(tmp_path / "short.wav", short), _write_wav(tmp_path / "long.wav", long)]
    prompt = f"First {AUDIO_MARKER} then {AUDIO_MARKER} done"
    _, inputs = _process(_model_path(test_data_path), prompt, og.Audios.open(*clips))

    # Clips are staged as one zero-padded tensor, each with its real length, in prompt order; the
    # placeholders follow the same order. The encoder itself runs once per clip on those lengths.
    assert _placeholder_runs(inputs["input_ids"].as_numpy()[0]) == [_num_tokens(len(short)), _num_tokens(len(long))]
    mel = inputs["audio_embeds"].as_numpy()
    assert mel.shape == (2, _num_frames(len(long)), NUM_MELS)
    np.testing.assert_array_equal(inputs["audio_lengths"].as_numpy(), [_num_frames(len(short)), _num_frames(len(long))])
    np.testing.assert_array_equal(inputs["audio_sizes"].as_numpy(), [_num_tokens(len(short)), _num_tokens(len(long))])
    assert np.all(mel[0, _num_frames(len(short)) :] == 0)
    np.testing.assert_allclose(mel[0, : _num_frames(len(short))], _reference_mel(short), atol=2e-3)
    np.testing.assert_allclose(mel[1], _reference_mel(long), atol=2e-3)


