def _generate(model_path: str, prompt: str, audios, num_tokens: int, chunk_size: int | None = None):
    model = og.Model(model_path)
    processor = model.create_multimodal_processor()
    params = og.GeneratorParams(model)
    options = {"do_sample": False, "max_length": 4096}
    if chunk_size is not None:
        options["chunk_size"] = chunk_size
    params.set_search_options(**options)

    inputs = processor(prompt, audios=audios)
    generator = og.Generator(model, params)
    generator.set_inputs(inputs)
    for _ in range(num_tokens):
        generator.generate_next_token()
    return generator, inputs


def _reference_generation(model_path: str, inputs, num_tokens: int) -> np.ndarray:
    """Greedy generation replayed with plain ONNX Runtime.

    Runs the speech model once per clip on that clip's own frames — the padding never reaches the
    encoder, which is what the runtime does and what the published encoder export requires — then
    scatters the concatenated features through the embedding model, and finally one decoder run per
    token carrying the KV cache and conv state by hand.
    """
    ort = pytest.importorskip("onnxruntime")
    config = json.loads((Path(model_path) / "genai_config.json").read_text())["model"]
    decoder_config = config["decoder"]
    speech = ort.InferenceSession(os.path.join(model_path, config["speech"]["filename"]))
    embedding = ort.InferenceSession(os.path.join(model_path, config["embedding"]["filename"]))
    decoder = ort.InferenceSession(os.path.join(model_path, decoder_config["filename"]))
    output_names = [output.name for output in decoder.get_outputs()]
    hidden_size = decoder_config["hidden_size"]

    input_ids = inputs["input_ids"].as_numpy()[0]
    tokens_per_clip = inputs["audio_sizes"].as_numpy()
    if tokens_per_clip.sum() > 0:
        mel = inputs["audio_embeds"].as_numpy()
        frames_per_clip = inputs["audio_lengths"].as_numpy()
        per_clip = [
            speech.run(None, {"mel_spectrogram": mel[i : i + 1, :frames], "mel_lengths": frames_per_clip[i : i + 1]})[
                0
            ][0]
            for i, frames in enumerate(frames_per_clip)
        ]
        audio_features = np.concatenate(
            [features[:count] for features, count in zip(per_clip, tokens_per_clip, strict=True)]
        )
    else:
        audio_features = np.zeros((0, hidden_size), np.float32)

    state = {}
    for layer, layer_type in enumerate(decoder_config["layer_types"]):
        if layer_type == "conv":
            state[f"past.{layer}.conv"] = np.zeros((1, hidden_size, decoder_config["conv_cache_size"]), np.float32)
        else:
            for kind in ("key", "value"):
                state[f"past_key_values.{layer}.{kind}"] = np.zeros(
                    (1, decoder_config["num_key_value_heads"], 0, decoder_config["head_size"]), np.float32
                )

    sequence = [int(token) for token in input_ids]
    step_ids = sequence
    for _ in range(num_tokens):
        embeds = embedding.run(
            None, {"input_ids": np.array([step_ids], dtype=np.int64), "audio_features": audio_features}
        )[0]
        feeds = {"inputs_embeds": embeds, "attention_mask": np.ones((1, len(sequence)), np.int64), **state}
        outputs = dict(zip(output_names, decoder.run(None, feeds), strict=True))
        for name in state:
            state[name] = outputs[name.replace("past_key_values.", "present.").replace("past.", "present.")]
        next_token = int(outputs["logits"][0, -1].argmax())
        sequence.append(next_token)
        step_ids = [next_token]
        audio_features = np.zeros((0, hidden_size), np.float32)
    return np.array(sequence, dtype=np.int32)


@pytest.mark.parametrize(
    "num_clips,chunk_size",
    [(0, None), (0, 3), (1, None), (1, 3), (1, 10), (2, None), (2, 5)],
    ids=["text", "text-chunk3", "audio", "audio-chunk3", "audio-chunk10", "two-clips", "two-clips-chunk5"],
)
def test_lfm2_audio_generation_matches_onnxruntime_reference(test_data_path, tmp_path, num_clips, chunk_size):
    # The decoder's logits read the conv state over the last few embeddings, so the prompt ends with
    # the audio: the first generated tokens depend on the scattered features, and the runtime only
    # matches the hand-carried reference if it passes both the features and the conv state along,
    # including across prefill chunk boundaries. The clips run longest first, so the last one is the
    # one the mel batch pads: feeding the encoder that padding instead of the clip's own frames
    # changes its final feature, and with it the first token generated.
    model_path = _model_path(test_data_path)
    clips = [_write_wav(tmp_path / f"{i}.wav", _synthetic_signal(1.7 - 0.7 * i, seed=10 + i)) for i in range(num_clips)]
    prompt = "<|startoftext|>Transcribe the following. " + " and ".join([AUDIO_MARKER] * num_clips)
    num_tokens = 6

    generator, inputs = _generate(model_path, prompt, og.Audios.open(*clips) if clips else None, num_tokens, chunk_size)
    input_ids = inputs["input_ids"].as_numpy()[0]
    assert chunk_size is None or len(input_ids) > chunk_size, "the prompt must span several chunks"

    np.testing.assert_array_equal(generator.get_sequence(0), _reference_generation(model_path, inputs, num_tokens))


def test_lfm2_audio_generation_depends_on_the_audio(test_data_path, tmp_path):
    model_path = _model_path(test_data_path)
    outputs = []
    for seed in (20, 21):
        clip = _write_wav(tmp_path / f"{seed}.wav", _synthetic_signal(0.5, seed=seed))
        generator, inputs = _generate(model_path, f"<|startoftext|>{AUDIO_MARKER}", og.Audios.open(clip), num_tokens=4)
        outputs.append(generator.get_sequence(0)[len(inputs["input_ids"].as_numpy()[0]) :].tolist())
