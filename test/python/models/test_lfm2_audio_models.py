    num_frames = int(inputs["audio_lengths"].as_numpy()[0])
    assert int(inputs["audio_sizes"].as_numpy()[0]) == math.ceil(num_frames / 4)
    assert _placeholder_runs(inputs["input_ids"].as_numpy()[0]) == [math.ceil(num_frames / 4)]


