def test_lfm2_audio_mel_matches_reference(test_data_path, tmp_path):
    samples = _synthetic_signal(2.0, seed=3)
    clip = _write_wav(tmp_path / "clip.wav", samples)
    _, inputs = _process(_model_path(test_data_path), AUDIO_MARKER, og.Audios.open(clip))
    mel = inputs["audio_embeds"].as_numpy()[0]

    reference = _reference_mel(samples)
    assert mel.shape == reference.shape
    np.testing.assert_allclose(mel, reference, atol=2e-3)
    # NeMo counts one frame fewer than the STFT produces; that last frame is zeroed but still fed.
    assert np.all(mel[-1] == 0)
    assert np.any(mel[-2] != 0)


